static int gen(const arg_item *spec, const arg_config *cfg, unsigned sh,
	       struct out *o)
{
	arg p;

	memset(o, 0, sizeof(*o));
	arg_init(&p, spec, cfg);
	return arg_completion(&p, sh, out_write, o);
}

static inline bool has(const struct out *o, const char *s)
{
	return strstr(o->data, s) != NULL;
}

